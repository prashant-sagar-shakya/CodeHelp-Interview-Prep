int matrixSum(vector<vector<int>> arr)
{
    int sum = 0;
    for (int i = 0; i < arr.size(); i++)
        sort(arr[i].begin(), arr[i].end());
    for (int i = 0; i < arr[0].size(); i++)
    {
        int maxi = 0;
        for (int j = 0; j < arr.size(); j++)
            maxi = max(maxi, arr[j][i]);
        sum += maxi;
    }
    return sum;
}

